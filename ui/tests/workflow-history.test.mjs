import assert from 'node:assert/strict';
import test from 'node:test';
import { fixture, openWorkspace, ownerAPI, pollOwner, seedSchema4 } from './helpers.mjs';

test('accepted schema4 history keeps its saved two-unit default and adds only explicit budget authority before workflow adoption', { timeout: 150000 }, async t => {
  const f = await fixture(t); const seed = await seedSchema4(f); const owner = await f.start(); const page = await openWorkspace(f, owner, { workflow: 'auto' });
  const old = await ownerAPI(owner, '/tasks/' + seed.taskId + '/workflow');
  assert.equal(old.status, 200); assert.equal(old.envelope.data.workflow, null);
  const policy = await ownerAPI(owner, '/routing/policy');
  assert.equal(policy.envelope.data.defaultBudget.admissionLimit, '2', 'migration preserves the saved default independently of task adoption');
  await page.locator('#task-list button').filter({ hasText: seed.taskId.slice(0, 8) }).click();
  await page.locator('#workflow-status').filter({ hasText: /standalone|adopt/i }).waitFor();
  let admissions = 0;
  page.on('request', r => { if (r.method() === 'POST' && /\/tasks(?:\/[a-f0-9]+\/attempts)?$/.test(new URL(r.url()).pathname)) admissions++; });
  const beforeBudget = await ownerAPI(owner, '/tasks/' + seed.taskId + '/budget');
  assert.equal(beforeBudget.envelope.data.budget, null, 'migration must not invent missing old authority');
  await page.locator('#task-routing-panel > summary').click();
  await page.locator('#budget-additional-admissions').fill('2'); await page.locator('#budget-new-window').fill('1800');
  const adoptedBudget = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/tasks/' + seed.taskId + '/budget-amendments');
  await page.locator('#adopt-task-budget').click(); const budgetResponse = await adoptedBudget;
  assert.equal(budgetResponse.status(), 200, JSON.stringify((await budgetResponse.json()).error));
  const granted = page.locator('#task-budget-facts dt').filter({ hasText: /^Granted admissions$/ });
  await granted.waitFor();
  assert.equal(await granted.locator('xpath=following-sibling::dd[1]').textContent(), '3');
  const adoptedAuthority = (await ownerAPI(owner, '/tasks/' + seed.taskId + '/budget')).envelope.data.budget;
  assert.equal(adoptedAuthority.grantedAdmissions, '3'); assert.equal(adoptedAuthority.consumedAdmissions, '1');
  assert.equal(adoptedAuthority.historicalAdmissions, '1'); assert.equal(adoptedAuthority.remainingAdmissions, '2');
  assert.equal(admissions, 0, 'budget adoption alone must launch no work');
  await page.locator('#adopt-task-workflow').click();
  await page.locator('#workflow-facts').filter({ hasText: /Workflow identity/ }).waitFor();
  assert.equal(admissions, 0, 'adoption alone must launch no work');
  const current = await ownerAPI(owner, '/tasks/' + seed.taskId + '/workflow');
  assert.ok(current.envelope.data.workflow);
  assert.equal(current.envelope.data.workflow.currentStepId, null);
  await page.locator('#workflow-status').filter({ hasText: /Run task/ }).waitFor();
  assert.equal(await page.locator('#advance-task-workflow').isEnabled(), false);
  await page.waitForFunction(() => !document.querySelector('#run-attempt')?.disabled && document.querySelector('#run-attempt')?.textContent === 'Run task');
  assert.notEqual(current.envelope.data.taskVersion, old.envelope.data.taskVersion);
  const budget = await ownerAPI(owner, '/tasks/' + seed.taskId + '/budget');
  assert.deepEqual(budget.envelope.data.budget, adoptedAuthority, 'workflow adoption neither adds authority nor refills the retained historical use');
  await page.locator('#workflow-panel > details > summary').click();
  await page.locator('#workflow-history-version').fill(old.envelope.data.taskVersion);
  await page.locator('#load-workflow-version').click();
  await page.locator('#workflow-status').filter({ hasText: /historical.*standalone|standalone.*historical/i }).waitFor();
  assert.equal(await page.locator('#advance-task-workflow').isEnabled(), false);
  assert.equal(await page.locator('#adopt-task-workflow').isEnabled(), false);
  assert.equal(admissions, 0);
});

test('adopted document starts its first author through Run task with captured execution while advance and recheck stay unavailable', { timeout: 90000 }, async t => {
  const f = await fixture(t, { files: { 'docs/note.md': 'CONTROLLED ADOPTION TEST DATA\r\nold\r\n東京\r\n' } });
  const owner = await f.start(); const page = await openWorkspace(f, owner, { workflow: 'auto' });
  await page.locator('#task-workflow').selectOption('author_only');
  await page.locator('#task-deliverable').selectOption('candidate');
  await page.locator('#task-fake-scenario').selectOption('workflow-document');
  await page.locator('#task-text').fill('Replace "old" with "new" in docs/note.md only');
  const admitted = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/tasks');
  await page.locator('#start-task').click(); const original = (await (await admitted).json()).data;
  await pollOwner(owner, '/attempts/' + original.attempt.id, data => data.phase === 'settled' && data.outcome === 'succeeded');
  await page.locator('#refresh-attempt').click();
  await page.waitForFunction(() => !document.querySelector('#adopt-task-workflow')?.disabled);
  const requests = [];
  page.on('request', request => {
    if (request.method() === 'POST' && new URL(request.url()).pathname.startsWith('/api/v1/tasks/' + original.task.id + '/')) requests.push({ path: new URL(request.url()).pathname, body: request.postDataJSON() });
  });
  const adopted = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/tasks/' + original.task.id + '/workflow/adopt');
  await page.locator('#adopt-task-workflow').click(); assert.equal((await adopted).status(), 200);
  const current = await pollOwner(owner, '/tasks/' + original.task.id + '/workflow', data => data.workflow?.nextAction === 'start_author');
  assert.equal(current.workflow.currentStepId, null); assert.equal(current.workflow.selectedCandidateId, null);
  const required = current.workflow.authority.checks.find(definition => definition.required && definition.builtinId === 'literal_document_replace/1');
  assert.ok(required, 'the actual adopted document captures a meaningful required proof');
  await page.locator('#workflow-status').filter({ hasText: /Run task/ }).waitFor();
  await page.locator('#workflow-panel > details > summary').click();
  await page.locator('#workflow-check-definition').selectOption(required.id);
  assert.equal(await page.locator('#advance-task-workflow').isEnabled(), false);
  assert.equal(await page.locator('#recheck-task-workflow').isEnabled(), false, 'a selected valid definition cannot run before an author subject exists');
  assert.deepEqual(requests.map(request => request.path), ['/api/v1/tasks/' + original.task.id + '/workflow/adopt']);
  const beforeRun = (await ownerAPI(owner, '/tasks/' + original.task.id)).envelope.data;
  // The current composer is unrelated to the adopted immutable execution scope.
  await page.locator('#task-fake-scenario').selectOption('response');
  await page.waitForFunction(() => !document.querySelector('#run-attempt')?.disabled && document.querySelector('#run-attempt')?.textContent === 'Run task');
  const started = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/tasks/' + original.task.id + '/attempts');
  await page.locator('#run-attempt').click(); const response = await started;
  assert.equal(response.status(), 201);
  const body = response.request().postDataJSON();
  assert.equal(body.taskVersion, current.taskVersion); assert.equal(body.expectedRevision, beforeRun.task.revision);
  assert.equal(body.executionMode, 'fake'); assert.equal(body.fakeScenario, 'workflow-document');
  await page.locator('#workflow-status').filter({ hasText: /completed/i }).waitFor();
  assert.equal(requests.filter(request => request.path.endsWith('/attempts')).length, 1);
  assert.equal(requests.filter(request => /\/workflow\/(?:advance|check)$/.test(request.path)).length, 0);
  const steps = (await ownerAPI(owner, '/tasks/' + original.task.id + '/workflow/steps')).envelope.data.items;
  assert.deepEqual(steps.map(step => step.role), ['author', 'check']);
  assert.equal(steps[0].executorKind, 'native'); assert.equal(steps[1].executorKind, 'local_check');
  assert.notEqual(steps[0].attemptId, original.attempt.id);
});
