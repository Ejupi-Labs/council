import assert from 'node:assert/strict';
import test from 'node:test';
import { fixture, fixtureRequestId, openWorkspace, ownerAPI, pollOwner } from './helpers.mjs';

test('required response review keeps the author as deliverable producer and accepts only its exact inspected bytes', { timeout: 60000 }, async t => {
  const f = await fixture(t); const owner = await f.start();
  const preference = (await ownerAPI(owner, '/workflow/preferences')).envelope.data;
  assert.equal((await ownerAPI(owner, '/workflow/preferences', 'PATCH', { requestId: fixtureRequestId(), expectedRevision: preference.revision, localMode: 'apply_verified_local' })).status, 200);
  const page = await openWorkspace(f, owner, { workflow: 'auto' });
  await page.locator('#task-review').selectOption('required');
  await page.locator('#task-required-evidence').fill('independent_review');
  await page.locator('#task-text').fill('CONTROLLED LOCAL RESPONSE TEST: explain this project without changing files; independently review the actual complete response.');
  const returned = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/tasks');
  await page.locator('#start-task').click(); const admission = (await (await returned).json()).data;
  await pollOwner(owner, '/tasks/' + admission.task.id + '/workflow', data => data.workflow?.nextAction === 'response_acceptance_pending' && data.workflow.nextOwner === 'user');
  await page.locator('#workflow-status').filter({ hasText: 'Response ready' }).waitFor();
  const steps = (await ownerAPI(owner, '/tasks/' + admission.task.id + '/workflow/steps')).envelope.data.items;
  assert.deepEqual(steps.map(s => s.role), ['author', 'review']);
  const author = (await ownerAPI(owner, '/attempts/' + steps[0].attemptId)).envelope.data;
  const reviewer = (await ownerAPI(owner, '/attempts/' + steps[1].attemptId)).envelope.data;
  const detail = (await ownerAPI(owner, '/tasks/' + admission.task.id)).envelope.data;
  assert.equal(detail.latestAttempt.id, reviewer.id);
  assert.equal(author.outcome, 'succeeded'); assert.equal(reviewer.outcome, 'succeeded');
  assert.notEqual(author.responseArtifactId, reviewer.responseArtifactId);
  const reviews = (await ownerAPI(owner, '/tasks/' + admission.task.id + '/workflow/reviews')).envelope.data.items;
  assert.equal(reviews.length, 1); assert.equal(reviews[0].outcome, 'approved');
  assert.equal(reviews[0].responseBinding.producerAttemptId, author.id);
  assert.equal(reviews[0].responseBinding.responseArtifactId, author.responseArtifactId);
  await page.locator('#read-response').click();
  await page.locator('#artifact-status').filter({ hasText: 'stream closed' }).waitFor();
  const answer = await page.locator('#artifact-output').textContent();
  assert.match(answer, /Council deterministic fake response/);
  assert.doesNotMatch(answer, /schemaVersion|inspectedEvidence/);
  await page.locator('#response-acceptance').waitFor();
  assert.equal(await page.locator('#accept-response').isEnabled(), false);

  // Inspecting the supporting reviewer must never make its JSON the answer.
  await page.locator('#workflow-panel > details > summary').click();
  await page.locator('#load-workflow-steps').click();
  await page.locator('#workflow-steps-list button').filter({ hasText: 'Inspect this stage' }).nth(1).click();
  await page.waitForFunction(id => document.querySelector('#attempt-facts')?.textContent.includes(id), reviewer.id);
  await page.locator('#read-response').click();
  await page.locator('#artifact-output').filter({ hasText: 'inspectedEvidence' }).waitFor();
  assert.equal(await page.locator('#response-acceptance').isVisible(), false);
  await page.locator('#workflow-steps-list button').filter({ hasText: 'Inspect this stage' }).first().click();
  await page.waitForFunction(id => document.querySelector('#attempt-facts')?.textContent.includes(id), author.id);
  await page.locator('#read-response').click();
  await page.locator('#artifact-status').filter({ hasText: 'stream closed' }).waitFor();
  await page.locator('#response-acceptance').waitFor();
  assert.equal(await page.locator('#artifact-output').textContent(), answer);
  const accepted = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/tasks/' + admission.task.id + '/response-acceptance');
  await page.locator('#reviewed-response').check(); await page.locator('#accept-response').click();
  const response = await accepted;
  assert.equal(response.status(), 200);
  assert.equal(response.request().postDataJSON().attemptId, author.id);
  assert.equal(response.request().postDataJSON().responseArtifactId, author.responseArtifactId);
  await page.locator('#workflow-status').filter({ hasText: /completed.*accepted/i }).waitFor();
  const workflow = (await ownerAPI(owner, '/tasks/' + admission.task.id + '/workflow')).envelope.data.workflow;
  assert.equal(workflow.completion.responseBinding.producerAttemptId, author.id);
  assert.equal(workflow.completion.responseBinding.responseArtifactId, author.responseArtifactId);
  const budget = (await ownerAPI(owner, '/tasks/' + admission.task.id + '/budget')).envelope.data.budget;
  assert.equal(budget.consumedAdmissions, '2');
  assert.equal((await ownerAPI(owner, '/tasks/' + admission.task.id + '/workflow/deliveries')).envelope.data.items.some(d => d.kind === 'local_application'), false);
});
