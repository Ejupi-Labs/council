import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fixture, fixtureRequestId, openWorkspace, ownerAPI } from './helpers.mjs';

test('saved prospective local scope applies only the verified document while preserving unrelated staged and working edits', { timeout: 60000 }, async t => {
  const original = '\ufeffCONTROLLED LOCAL WORKFLOW DATA\r\nold\r\n東京\r\n';
  const f = await fixture(t, { files: { 'docs/note.md': original } }); const owner = await f.start();
  const preference = await ownerAPI(owner, '/workflow/preferences');
  const saved = await ownerAPI(owner, '/workflow/preferences', 'PATCH', { requestId: fixtureRequestId(), expectedRevision: preference.envelope.data.revision, localMode: 'apply_verified_local' });
  assert.equal(saved.status, 200);
  const page = await openWorkspace(f, owner, { workflow: 'auto' }); await page.locator('#task-deliverable').selectOption('candidate');
  await page.locator('#task-fake-scenario').selectOption('workflow-document');
  await page.locator('#task-text').fill('Replace "old" with "new" in docs/note.md only');
  const admitted = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/v1/tasks');
  await page.locator('#start-task').click(); const admission = (await (await admitted).json()).data;
  await page.locator('#workflow-status').filter({ hasText: /completed.*applied|applied.*completed/i }).waitFor();
  assert.equal(await readFile(path.join(f.project, 'docs/note.md'), 'utf8'), original.replace('old', 'new'));
  assert.equal(await readFile(path.join(f.project, 'hello.txt'), 'utf8'), 'unstaged\n');
  assert.deepEqual(await readFile(path.join(f.project, '.git/index')), f.indexBefore);
  const deliveries = await ownerAPI(owner, '/tasks/' + admission.task.id + '/workflow/deliveries');
  assert.equal(deliveries.status, 200); assert.ok(deliveries.envelope.data.items.some(d => d.kind === 'local_application' && d.operation?.status === 'applied'));
  const steps = await ownerAPI(owner, '/tasks/' + admission.task.id + '/workflow/steps');
  assert.ok(steps.envelope.data.items.some(s => s.executorKind === 'local_application' && s.role === 'local_delivery'));
  const budget = await ownerAPI(owner, '/tasks/' + admission.task.id + '/budget');
  assert.equal(budget.envelope.data.budget.consumedAdmissions, '1');
  await page.locator('#workflow-panel > details > summary').click();
  await page.locator('#load-workflow-deliveries').click();
  await page.locator('#workflow-deliveries-list').filter({ hasText: 'applied' }).waitFor();
  await page.locator('#load-workflow-steps').click();
  await page.locator('#workflow-steps-list button').filter({ hasText: 'Inspect this stage' }).first().click();
  await page.getByText('Source, candidate and observed native details', { exact: true }).click();
  await page.locator('#attempt-facts').filter({ hasText: 'Candidate status at creation' }).waitFor();
  const author = steps.envelope.data.items.find(step => step.role === 'author');
  const retained = (await ownerAPI(owner, '/attempts/' + author.attemptId)).envelope.data;
  assert.equal(retained.candidate.verification, 'pending'); assert.equal(retained.candidate.integration, 'not_performed');
  const creationFacts = await page.locator('#attempt-facts').textContent();
  assert.match(creationFacts, /Candidate status at creation.*Verification pending.*integration not performed.*Immutable creation facts/s);
  assert.doesNotMatch(creationFacts, /Candidate verification and integration/);
  assert.match(await page.locator('#workflow-status').textContent(), /completed.*applied/i);
  assert.doesNotMatch(await page.locator('#workflow-facts').textContent(), /published|0 tokens|free|savings/i);
});
